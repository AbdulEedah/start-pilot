/**
 * Roadmap Blueprint Export Utility
 *
 * Generates and downloads the roadmap blueprint directly in the browser
 * as either a PDF or Plain Text file. Works 100% offline without backend reliance.
 */
import { jsPDF } from "jspdf";

export interface ExportRoadmapItem {
  id: string;
  title: string;
  description: string;
  category: string;
  priority: string;
  timeframe: string;
  status: "pending" | "in-progress" | "completed";
}

export interface ExportRoadmapData {
  title: string;
  items: ExportRoadmapItem[];
  totalWeeks?: number;
}

export interface ExportUserContext {
  fullName?: string;
  email?: string;
  sectorName?: string;
  problemStatement?: string;
  country?: string;
}

/**
 * Download a plain text file directly in the browser.
 */
function triggerFileDownload(content: string, filename: string, mimeType: string) {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const link = document.createElement("a");
  link.href = url;
  link.download = filename;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}

/**
 * Export the roadmap as a clean Plain Text (.txt) file.
 */
export function exportRoadmapToPlainText(
  roadmap: ExportRoadmapData,
  userContext: ExportUserContext
): void {
  const dateStr = new Date().toLocaleDateString("en-US", {
    year: "numeric",
    month: "long",
    day: "numeric",
  });
  const founder = userContext.fullName || userContext.email || "Founder";
  const sector = userContext.sectorName || "Startup";
  const cleanSector = sector.replace(/[^a-zA-Z0-9_-]/g, "");

  const totalTasks = roadmap.items.length;
  const completedTasks = roadmap.items.filter((i) => i.status === "completed").length;

  let text = "";
  text += "================================================================================\n";
  text += "                 START PILOT — STARTUP EXECUTION BLUEPRINT                      \n";
  text += "================================================================================\n\n";

  text += `Venture Title:     ${roadmap.title}\n`;
  text += `Target Sector:     ${sector}\n`;
  text += `Founder:           ${founder} (${userContext.email || "Confidential"})\n`;
  if (userContext.country) {
    text += `Location:          ${userContext.country}\n`;
  }
  text += `Generated Date:    ${dateStr}\n`;
  text += `Total Milestones:  ${totalTasks} Tasks (${completedTasks} Completed)\n`;
  if (userContext.problemStatement) {
    text += `Core Problem:      ${userContext.problemStatement}\n`;
  }
  text += "\n";
  text += "--------------------------------------------------------------------------------\n";
  text += "                        EXECUTION PHASES & MILESTONES                           \n";
  text += "--------------------------------------------------------------------------------\n\n";

  // Group items by category
  const categories: Record<string, ExportRoadmapItem[]> = {};
  roadmap.items.forEach((item) => {
    const cat = item.category.toUpperCase();
    if (!categories[cat]) categories[cat] = [];
    categories[cat].push(item);
  });

  for (const [category, items] of Object.entries(categories)) {
    text += `[${category} EXECUTION]\n`;
    text += "----------------------------------------\n";
    items.forEach((item, index) => {
      const isDone = item.status === "completed";
      const statusTag = isDone ? "[X] COMPLETED" : item.status === "in-progress" ? "[-] IN PROGRESS" : "[ ] PENDING";
      const prioTag = (item.priority || "MEDIUM").toUpperCase();
      const timeTag = item.timeframe ? ` • ${item.timeframe}` : "";

      text += `${index + 1}. ${statusTag} ${item.title} [${prioTag}${timeTag}]\n`;
      if (item.description) {
        text += `   Description: ${item.description}\n`;
      }
      text += "\n";
    });
    text += "\n";
  }

  text += "================================================================================\n";
  text += "Generated by Start Pilot • Empowering Early-Stage Founders to Build & Scale     \n";
  text += "================================================================================\n";

  triggerFileDownload(text, `StartPilot_Roadmap_${cleanSector}.txt`, "text/plain;charset=utf-8");
}

/**
 * Export the roadmap as a beautifully formatted PDF document.
 * Operates 100% in the client browser with jsPDF.
 */
export function exportRoadmapToPdf(
  roadmap: ExportRoadmapData,
  userContext: ExportUserContext
): void {
  const doc = new jsPDF({
    orientation: "portrait",
    unit: "mm",
    format: "a4",
  });

  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();
  const margin = 15;
  const contentWidth = pageWidth - margin * 2;

  let y = 18;

  const founder = userContext.fullName || userContext.email || "Founder";
  const sector = userContext.sectorName || "Startup";
  const cleanSector = sector.replace(/[^a-zA-Z0-9_-]/g, "");
  const dateStr = new Date().toLocaleDateString("en-US", {
    year: "numeric",
    month: "long",
    day: "numeric",
  });

  const totalTasks = roadmap.items.length;
  const completedTasks = roadmap.items.filter((i) => i.status === "completed").length;

  const checkPageBreak = (neededHeight: number) => {
    if (y + neededHeight > pageHeight - 18) {
      doc.addPage();
      y = 18;
      drawHeaderFooter();
    }
  };

  const drawHeaderFooter = () => {
    doc.saveGraphicsState();
    // Header line
    doc.setDrawColor(226, 232, 240);
    doc.setLineWidth(0.3);
    doc.line(margin, 12, pageWidth - margin, 12);
    doc.setFont("helvetica", "normal");
    doc.setFontSize(7.5);
    doc.setTextColor(148, 163, 184);
    doc.text("Start Pilot — Confidential Startup Execution Blueprint", margin, 9);

    // Footer line
    doc.line(margin, pageHeight - 12, pageWidth - margin, pageHeight - 12);
    doc.text("Generated by Start Pilot • Empowering Early-Stage Founders", margin, pageHeight - 8);
    const pageNo = (doc as any).internal.getCurrentPageInfo().pageNumber;
    doc.text(`Page ${pageNo}`, pageWidth - margin, pageHeight - 8, { align: "right" });
    doc.restoreGraphicsState();
  };

  drawHeaderFooter();

  // Brand Pill
  doc.setFont("helvetica", "bold");
  doc.setFontSize(8);
  doc.setTextColor(79, 70, 229); // Primary Indigo
  doc.text("START PILOT", margin, y);
  y += 6;

  // Title
  doc.setFont("helvetica", "bold");
  doc.setFontSize(18);
  doc.setTextColor(15, 23, 42); // Slate-900
  doc.text("Startup Execution Blueprint", margin, y);
  y += 5;

  // Subtitle
  doc.setFont("helvetica", "normal");
  doc.setFontSize(9);
  doc.setTextColor(100, 116, 139); // Slate-500
  doc.text(`Prepared for: ${founder} • Generated on ${dateStr}`, margin, y);
  y += 8;

  // Metadata Box
  doc.setDrawColor(226, 232, 240);
  doc.setFillColor(248, 250, 252);
  doc.roundedRect(margin, y, contentWidth, 24, 2, 2, "FD");

  doc.setFontSize(8);
  // Column 1
  doc.setFont("helvetica", "bold");
  doc.setTextColor(71, 85, 105);
  doc.text("Target Sector:", margin + 4, y + 6);
  doc.text("Founder:", margin + 4, y + 13);
  doc.text("Milestones:", margin + 4, y + 20);

  doc.setFont("helvetica", "normal");
  doc.setTextColor(15, 23, 42);
  doc.text(sector, margin + 28, y + 6);
  doc.text(String(userContext.email || founder), margin + 28, y + 13);
  doc.text(`${totalTasks} Tasks (${completedTasks} Completed)`, margin + 28, y + 20);

  // Column 2
  const col2X = margin + 100;
  doc.setFont("helvetica", "bold");
  doc.setTextColor(71, 85, 105);
  doc.text("Venture:", col2X, y + 6);
  doc.text("Location:", col2X, y + 13);
  doc.text("Format:", col2X, y + 20);

  doc.setFont("helvetica", "normal");
  doc.setTextColor(15, 23, 42);
  const vTitle = roadmap.title.length > 32 ? roadmap.title.substring(0, 30) + "..." : roadmap.title;
  doc.text(vTitle, col2X + 18, y + 6);
  doc.text(userContext.country || "Global", col2X + 18, y + 13);
  doc.text("Official StartPilot PDF Blueprint", col2X + 18, y + 20);

  y += 30;

  // Group tasks by category
  const categories: Record<string, ExportRoadmapItem[]> = {};
  roadmap.items.forEach((item) => {
    const cat = item.category || "product";
    if (!categories[cat]) categories[cat] = [];
    categories[cat].push(item);
  });

  const catColors: Record<string, [number, number, number]> = {
    product: [79, 70, 229],
    marketing: [2, 132, 199],
    operations: [13, 148, 136],
    finance: [22, 163, 74],
    legal: [217, 119, 6],
    funding: [124, 58, 237],
    team: [219, 39, 119],
  };

  for (const [catName, items] of Object.entries(categories)) {
    checkPageBreak(25);

    const rgb = catColors[catName.toLowerCase()] || [79, 70, 229];

    // Category Header Bar
    doc.setFillColor(rgb[0], rgb[1], rgb[2]);
    doc.rect(margin, y, contentWidth, 7, "F");

    doc.setFont("helvetica", "bold");
    doc.setFontSize(8.5);
    doc.setTextColor(255, 255, 255);
    doc.text(`${catName.toUpperCase()} EXECUTION`, margin + 4, y + 4.8);

    doc.setFont("helvetica", "normal");
    doc.text(`${items.length} Tasks`, pageWidth - margin - 4, y + 4.8, { align: "right" });
    y += 9;

    // Render Each Task
    for (const task of items) {
      checkPageBreak(20);

      const isCompleted = task.status === "completed";
      const statusIcon = isCompleted ? "[X]" : "[ ]";
      const statusText = isCompleted ? "Completed" : "Pending";
      const priorityText = (task.priority || "medium").toUpperCase();
      const timeframeText = task.timeframe || "";

      // Task background box
      doc.setDrawColor(241, 245, 249);
      doc.setFillColor(isCompleted ? 250 : 255, 250, 250);

      // Title line
      doc.setFont("helvetica", "bold");
      doc.setFontSize(8.5);
      doc.setTextColor(isCompleted ? 22 : 15, isCompleted ? 163 : 23, isCompleted ? 74 : 42);
      doc.text(`${statusIcon} ${task.title}`, margin + 2, y + 3);

      // Priority and Timeframe tag
      doc.setFont("helvetica", "normal");
      doc.setFontSize(7.5);
      doc.setTextColor(100, 116, 139);
      const tagText = `${priorityText}${timeframeText ? " • " + timeframeText : ""} • ${statusText}`;
      doc.text(tagText, pageWidth - margin - 2, y + 3, { align: "right" });

      y += 6;

      // Description text wrapped
      if (task.description) {
        doc.setFont("helvetica", "normal");
        doc.setFontSize(7.5);
        doc.setTextColor(71, 85, 105);
        const splitDesc = doc.splitTextToSize(task.description, contentWidth - 4);
        checkPageBreak(splitDesc.length * 3.5 + 3);
        doc.text(splitDesc, margin + 2, y + 2);
        y += splitDesc.length * 3.5 + 3;
      } else {
        y += 2;
      }

      // Separator line between tasks
      doc.setDrawColor(241, 245, 249);
      doc.line(margin + 2, y, pageWidth - margin - 2, y);
      y += 3;
    }

    y += 4;
  }

  doc.save(`StartPilot_Roadmap_${cleanSector}.pdf`);
}

