"""
PDF generation service for StartPilot Roadmaps using ReportLab.
"""
import io
from datetime import datetime
from reportlab.lib.pagesizes import letter
from reportlab.lib import colors
from reportlab.platypus import (
    SimpleDocTemplate,
    Paragraph,
    Spacer,
    Table,
    TableStyle,
    HRFlowable,
    KeepTogether,
)
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.pdfgen import canvas


class NumberedCanvas(canvas.Canvas):
    """Two-pass canvas to dynamically compute and print total page count."""

    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_number(num_pages)
            super().showPage()
        super().save()

    def draw_page_number(self, page_count):
        self.saveState()
        self.setFont("Helvetica", 8)
        self.setFillColor(colors.HexColor("#64748B"))
        # Header line
        self.setStrokeColor(colors.HexColor("#E2E8F0"))
        self.setLineWidth(0.5)
        self.line(40, letter[1] - 30, letter[0] - 40, letter[1] - 30)
        self.drawString(40, letter[1] - 25, "Start Pilot — Confidential Startup Execution Blueprint")
        
        # Footer
        self.line(40, 38, letter[0] - 40, 38)
        self.drawString(40, 26, "Generated by Start Pilot • Empowering Early-Stage Founders")
        self.drawRightString(letter[0] - 40, 26, f"Page {self._pageNumber} of {page_count}")
        self.restoreState()


def generate_roadmap_pdf(roadmap, profile, user) -> bytes:
    """
    Generate a clean, professional PDF document of the founder's roadmap.

    Args:
        roadmap: Roadmap instance with categories and tasks.
        profile: StartupProfile instance.
        user:    User instance.

    Returns:
        bytes: The generated PDF binary data.
    """
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=letter,
        leftMargin=40,
        rightMargin=40,
        topMargin=45,
        bottomMargin=50,
    )

    styles = getSampleStyleSheet()

    # Custom styles
    brand_style = ParagraphStyle(
        "BrandHeader",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=20,
        leading=24,
        textColor=colors.HexColor("#0F172A"),
    )
    subtitle_style = ParagraphStyle(
        "Subtitle",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=10,
        leading=14,
        textColor=colors.HexColor("#64748B"),
    )
    section_title_style = ParagraphStyle(
        "SectionTitle",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=13,
        leading=17,
        textColor=colors.HexColor("#1E293B"),
    )
    task_title_style = ParagraphStyle(
        "TaskTitle",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=10,
        leading=13,
        textColor=colors.HexColor("#0F172A"),
    )
    task_desc_style = ParagraphStyle(
        "TaskDesc",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=8.5,
        leading=12,
        textColor=colors.HexColor("#334155"),
    )
    meta_label = ParagraphStyle(
        "MetaLabel",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=8.5,
        leading=11,
        textColor=colors.HexColor("#475569"),
    )
    meta_val = ParagraphStyle(
        "MetaVal",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=8.5,
        leading=11,
        textColor=colors.HexColor("#0F172A"),
    )

    story = []

    # 1. Header Banner
    story.append(Spacer(1, 10))
    story.append(Paragraph("START PILOT", ParagraphStyle(
        "TopPill", fontName="Helvetica-Bold", fontSize=9, textColor=colors.HexColor("#4F46E5"), leading=11
    )))
    story.append(Spacer(1, 4))
    startup_name = getattr(profile, "background_story", "") or "Startup Venture"
    if len(startup_name) > 60:
        startup_name = startup_name[:57] + "..."
    story.append(Paragraph("Startup Execution Blueprint", brand_style))
    story.append(Spacer(1, 4))
    date_str = datetime.now().strftime("%B %d, %Y")
    founder_name = getattr(user, "full_name", "") or getattr(user, "email", "Founder")
    story.append(Paragraph(f"Prepared for: <b>{founder_name}</b> • Generated on {date_str}", subtitle_style))
    story.append(Spacer(1, 14))

    # 2. Executive Overview Table
    sector_name = getattr(profile, "get_sector_display", lambda: getattr(profile, "sector", "Technology"))()
    country_name = getattr(profile, "country", "Global") or "Global"
    total_weeks = getattr(roadmap, "total_weeks", 12)

    categories = list(roadmap.categories.all().prefetch_related("tasks"))
    total_tasks = sum(cat.tasks.count() for cat in categories)
    completed_tasks = sum(cat.tasks.filter(is_completed=True).count() for cat in categories)

    meta_data = [
        [
            Paragraph("<b>Target Sector:</b>", meta_label),
            Paragraph(str(sector_name), meta_val),
            Paragraph("<b>Location:</b>", meta_label),
            Paragraph(f"{getattr(profile, 'city', '')} {country_name}".strip(), meta_val),
        ],
        [
            Paragraph("<b>Total Timeline:</b>", meta_label),
            Paragraph(f"{total_weeks} Weeks", meta_val),
            Paragraph("<b>Milestones:</b>", meta_label),
            Paragraph(f"{total_tasks} Tasks ({completed_tasks} completed)", meta_val),
        ],
        [
            Paragraph("<b>Core Problem:</b>", meta_label),
            Paragraph(str(getattr(profile, "problem", "Market solution")), meta_val),
            Paragraph("<b>Founder:</b>", meta_label),
            Paragraph(str(getattr(user, "email", "")), meta_val),
        ],
    ]

    meta_table = Table(meta_data, colWidths=[90, 180, 80, 180])
    meta_table.setStyle(
        TableStyle([
            ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#F8FAFC")),
            ("BOX", (0, 0), (-1, -1), 1, colors.HexColor("#E2E8F0")),
            ("INNERGRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#EDF2F7")),
            ("TOPPADDING", (0, 0), (-1, -1), 6),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
            ("LEFTPADDING", (0, 0), (-1, -1), 8),
            ("RIGHTPADDING", (0, 0), (-1, -1), 8),
            ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ])
    )
    story.append(meta_table)
    story.append(Spacer(1, 18))

    # 3. Categories & Tasks
    cat_colors = {
        "product": colors.HexColor("#4F46E5"),
        "marketing": colors.HexColor("#0284C7"),
        "operations": colors.HexColor("#0D9488"),
        "finance": colors.HexColor("#16A34A"),
        "legal": colors.HexColor("#D97706"),
    }

    priority_colors = {
        "critical": colors.HexColor("#DC2626"),
        "high": colors.HexColor("#EA580C"),
        "medium": colors.HexColor("#2563EB"),
        "low": colors.HexColor("#64748B"),
    }

    for cat in categories:
        cat_tasks = list(cat.tasks.all().order_by("order", "start_week"))
        if not cat_tasks:
            continue

        cat_color = cat_colors.get(cat.name.lower(), colors.HexColor("#4F46E5"))
        
        # Category header bar
        cat_header_data = [[
            Paragraph(f"<b>{cat.name.upper()} EXECUTION</b>", ParagraphStyle(
                "CatHead", fontName="Helvetica-Bold", fontSize=10.5, textColor=colors.white, leading=13
            )),
            Paragraph(f"{len(cat_tasks)} Milestones", ParagraphStyle(
                "CatCount", fontName="Helvetica", fontSize=9, textColor=colors.white, alignment=2, leading=13
            ))
        ]]
        cat_header_table = Table(cat_header_data, colWidths=[380, 150])
        cat_header_table.setStyle(
            TableStyle([
                ("BACKGROUND", (0, 0), (-1, -1), cat_color),
                ("TOPPADDING", (0, 0), (-1, -1), 5),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
                ("LEFTPADDING", (0, 0), (-1, -1), 8),
                ("RIGHTPADDING", (0, 0), (-1, -1), 8),
                ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
            ])
        )

        task_rows = []
        for task in cat_tasks:
            status_text = "[X] Done" if task.is_completed else "[ ] Pending"
            status_color = colors.HexColor("#16A34A") if task.is_completed else colors.HexColor("#64748B")
            prio = (task.priority or "medium").lower()
            prio_color = priority_colors.get(prio, colors.HexColor("#2563EB"))

            duration_str = f"Week {task.start_week}"
            if task.end_week and task.end_week != task.start_week:
                duration_str += f"-{task.end_week}"

            header_line = Paragraph(
                f"<b>{task.title}</b> &nbsp;&nbsp;<font color='{prio_color.hexval()}'><b>[{prio.upper()}]</b></font> &nbsp;•&nbsp; <font color='#64748B'>{duration_str}</font>",
                task_title_style,
            )
            desc_line = Paragraph(task.description or "No description provided.", task_desc_style)
            status_line = Paragraph(
                f"<b>Status:</b> <font color='{status_color.hexval()}'>{status_text}</font>",
                ParagraphStyle("Stat", fontName="Helvetica", fontSize=8, leading=10, textColor=status_color)
            )

            task_cell = [header_line, Spacer(1, 2), desc_line, Spacer(1, 2), status_line]
            task_rows.append([task_cell])

        tasks_table = Table(task_rows, colWidths=[530])
        tasks_table.setStyle(
            TableStyle([
                ("BACKGROUND", (0, 0), (-1, -1), colors.white),
                ("BOX", (0, 0), (-1, -1), 1, colors.HexColor("#E2E8F0")),
                ("INNERGRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#F1F5F9")),
                ("TOPPADDING", (0, 0), (-1, -1), 6),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
                ("LEFTPADDING", (0, 0), (-1, -1), 8),
                ("RIGHTPADDING", (0, 0), (-1, -1), 8),
            ])
        )

        story.append(KeepTogether([cat_header_table, tasks_table]))
        story.append(Spacer(1, 14))

    doc.build(story, canvasmaker=NumberedCanvas)
    return buffer.getvalue()

